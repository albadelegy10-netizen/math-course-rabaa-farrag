import React, { useState } from 'react';
import { CourseCategory } from '../types';
import { generateQuestionsFromAI } from '../geminiService';
import { lessonService } from '../lessonService';
import { questionService } from '../questionService';
import { useNavigate } from 'react-router-dom';
import { Wand2, Loader2, CheckCircle2, FileText, BookOpen } from 'lucide-react';

const AIGenerator: React.FC = () => {
  const navigate = useNavigate();
  const [course, setCourse] = useState<CourseCategory>('DSAT');
  const [contentType, setContentType] = useState<'lesson' | 'exam'>('lesson');
  const [topic, setTopic] = useState('');
  const [count, setCount] = useState(10);
  const [isGenerating, setIsGenerating] = useState(false);
  const [progress, setProgress] = useState('');
  const [generatedLessonId, setGeneratedLessonId] = useState<string | null>(null);

  const handleGenerate = async () => {
    if (!topic.trim()) {
      alert("Please enter a topic.");
      return;
    }

    setIsGenerating(true);
    setProgress('Initializing AI Generator...');
    setGeneratedLessonId(null);

    try {
      // Create a prompt based on requirements
      const promptText = `Generate a Math ${contentType} for ${course} course on the topic of "${topic}".
      Provide exactly ${count} multiple-choice questions.`;

      setProgress('Generating content with AI... (this may take a minute)');
      
      const newQuestions = await generateQuestionsFromAI(promptText, count, (msg) => setProgress(msg));

      if (newQuestions && newQuestions.length > 0) {
        setProgress('Saving generated content...');
        const newId = `ai_${Date.now()}`;
        const newLesson = {
          id: newId,
          title: `${topic} (${course} ${contentType === 'lesson' ? 'Lesson' : 'Exam'})`,
          type: contentType,
          course: course,
          description: `AI-Generated ${contentType} for ${course} - ${topic}`,
          duration: contentType === 'exam' ? 60 : 30,
          studyNotes: `# ${topic}\n\nGenerated by AI for ${course}.`
        };

        // Assign proper IDs to questions
        const mappedQuestions = newQuestions.map((q: any, i: number) => ({
          ...q,
          id: i + 1,
          category: topic
        }));

        await lessonService.saveLesson(newLesson as any);
        await questionService.saveQuestions(newId, mappedQuestions);

        setGeneratedLessonId(newId);
        setProgress('');
      } else {
        alert("Failed to generate content.");
      }
    } catch (error) {
      console.error(error);
      alert("An error occurred during generation.");
    } finally {
      setIsGenerating(false);
    }
  };

  return (
    <div className="p-8 max-w-4xl mx-auto">
      <div className="flex items-center space-x-4 mb-8">
        <div className="p-3 bg-purple-100 text-purple-600 rounded-xl shadow-inner">
          <Wand2 className="w-8 h-8" />
        </div>
        <div>
          <h1 className="text-3xl font-black text-gray-900 tracking-tight">AI Content Generator</h1>
          <p className="text-gray-500 mt-1 font-medium">Create tailored Math exams and lessons with AI.</p>
        </div>
      </div>

      <div className="bg-white rounded-2xl shadow-xl border border-gray-100 p-8 mb-8 overflow-hidden relative">
        <div className="grid grid-cols-1 md:grid-cols-2 gap-8 mb-8">
          <div className="space-y-6">
            <div>
              <label className="block text-sm font-bold text-gray-700 mb-2">Course Name</label>
              <select
                value={course}
                onChange={(e) => setCourse(e.target.value as CourseCategory)}
                className="w-full p-3 border-2 border-gray-200 rounded-xl focus:ring-4 focus:ring-purple-500/20 focus:border-purple-500 transition-all text-gray-800 font-medium"
              >
                <option value="EST1">EST 1</option>
                <option value="EST2">EST 2</option>
                <option value="DSAT">DSAT</option>
                <option value="ACT1">ACT 1</option>
                <option value="ACT2">ACT 2</option>
              </select>
            </div>

            <div>
              <label className="block text-sm font-bold text-gray-700 mb-2">Content Type</label>
              <div className="flex space-x-4">
                <button
                  onClick={() => setContentType('lesson')}
                  className={`flex-1 py-3 px-4 rounded-xl font-bold flex items-center justify-center transition-all ${
                    contentType === 'lesson' 
                      ? 'bg-purple-100 text-purple-700 border-2 border-purple-500' 
                      : 'bg-gray-50 text-gray-500 border-2 border-transparent hover:bg-gray-100'
                  }`}
                >
                  <BookOpen className="w-5 h-5 mr-2" /> Lesson
                </button>
                <button
                  onClick={() => setContentType('exam')}
                  className={`flex-1 py-3 px-4 rounded-xl font-bold flex items-center justify-center transition-all ${
                    contentType === 'exam' 
                      ? 'bg-indigo-100 text-indigo-700 border-2 border-indigo-500' 
                      : 'bg-gray-50 text-gray-500 border-2 border-transparent hover:bg-gray-100'
                  }`}
                >
                  <FileText className="w-5 h-5 mr-2" /> Exam
                </button>
              </div>
            </div>
            
            <div>
              <label className="block text-sm font-bold text-gray-700 mb-2">Number of Questions</label>
              <input
                type="number"
                min="1"
                max="50"
                value={count}
                onChange={(e) => setCount(Number(e.target.value))}
                className="w-full p-3 border-2 border-gray-200 rounded-xl focus:ring-4 focus:ring-purple-500/20 focus:border-purple-500 transition-all text-gray-800 font-medium"
              />
            </div>
          </div>

          <div>
            <label className="block text-sm font-bold text-gray-700 mb-2">Topic or Focus Area</label>
            <textarea
              value={topic}
              onChange={(e) => setTopic(e.target.value)}
              placeholder="e.g. Advanced Algebra, Circle Theorems, Data Analysis..."
              className="w-full h-[220px] p-4 border-2 border-gray-200 rounded-xl focus:ring-4 focus:ring-purple-500/20 focus:border-purple-500 transition-all resize-none text-gray-800 font-medium"
            />
          </div>
        </div>

        <div className="flex justify-end pt-4 border-t border-gray-100">
          <button
            onClick={handleGenerate}
            disabled={isGenerating || !topic.trim()}
            className="flex items-center justify-center px-8 py-4 bg-gradient-to-r from-purple-600 to-indigo-600 text-white rounded-xl font-black text-lg hover:shadow-lg hover:shadow-purple-500/30 transition-all disabled:opacity-50 disabled:cursor-not-allowed transform hover:-translate-y-1"
          >
            {isGenerating ? (
              <>
                <Loader2 className="w-6 h-6 mr-3 animate-spin" />
                Generating...
              </>
            ) : (
              <>
                <Wand2 className="w-6 h-6 mr-3" />
                Generate {contentType === 'lesson' ? 'Lesson' : 'Exam'}
              </>
            )}
          </button>
        </div>

        {isGenerating && progress && (
          <div className="mt-6 p-4 bg-purple-50 rounded-xl border border-purple-100 flex items-center justify-center animate-pulse">
            <span className="text-purple-700 font-bold text-center">{progress}</span>
          </div>
        )}

        {generatedLessonId && !isGenerating && (
          <div className="mt-6 p-6 bg-green-50 border-2 border-green-200 rounded-xl text-center">
            <div className="w-16 h-16 bg-green-100 text-green-600 rounded-full flex items-center justify-center mx-auto mb-4">
              <CheckCircle2 className="w-8 h-8" />
            </div>
            <h3 className="text-xl font-black text-green-800 mb-2">Generation Complete!</h3>
            <p className="text-green-700 font-medium mb-6">Your new {contentType} has been successfully created.</p>
            <div className="flex justify-center space-x-4">
               <button
                  onClick={() => navigate(`/lesson/${generatedLessonId}`)}
                  className="px-6 py-2 bg-white text-green-700 border-2 border-green-300 rounded-lg font-bold hover:bg-green-100 transition-colors"
                >
                  View {contentType === 'lesson' ? 'Lesson' : 'Exam'}
                </button>
                <button
                  onClick={() => navigate(`/editor/${generatedLessonId}`)}
                  className="px-6 py-2 bg-green-600 text-white rounded-lg font-bold hover:bg-green-700 transition-colors shadow-md"
                >
                  Edit Content
                </button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};

export default AIGenerator;
