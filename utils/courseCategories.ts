export const getCourseCategories = (courseName?: string): string[] => {
  if (!courseName) return COURSE_CATEGORIES.EST1;
  const upper = courseName.toUpperCase().trim();
  if (upper.includes('EST2')) return COURSE_CATEGORIES.EST2;
  if (upper.includes('ACT2')) return COURSE_CATEGORIES.ACT2;
  if (upper.includes('DSAT') || upper.includes('SAT')) return COURSE_CATEGORIES.DSAT;
  if (upper.includes('ACT1') || upper.includes('ACT')) return COURSE_CATEGORIES.ACT1;
  return COURSE_CATEGORIES.EST1;
};
